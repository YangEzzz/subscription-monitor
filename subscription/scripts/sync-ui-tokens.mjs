import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Design px → rpx at 390px. Keep hairlines at one physical CSS px.
const source = new URL("../../ui-redesign/assets/tokens.css", import.meta.url);
const output = new URL("../styles/_design-tokens.scss", import.meta.url);
const adapt = (value) =>
  value.replace(/(-?\d*\.?\d+)px\b/g, (_, value) => {
    const px = Number(value);
    return Math.abs(px) === 1
      ? `${px}px`
      : `${Number(((px * 750) / 390).toFixed(4))}rpx`;
  });
const css = readFileSync(source, "utf8").replace(":root", "page");
const result =
  "// Generated by scripts/sync-ui-tokens.mjs from ui-redesign/assets/tokens.css.\n" +
  adapt(css);
const keys = [
  "blue",
  "violet",
  "orange",
  "gold",
  "ink-4",
  "surface-sunken",
  "cat-video",
  "cat-cloud",
  "cat-music",
];
const values = Object.fromEntries(
  [...css.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)]
    .filter((match) => keys.includes(match[1]))
    .map((match) => [match[1], match[2].trim()]),
);
const palette = new URL("../styles/ui-palette.js", import.meta.url);
const paletteSource =
  "// Generated by scripts/sync-ui-tokens.mjs; canvas cannot resolve CSS variables.\nexport const UI_COLORS = " +
  JSON.stringify(values, null, 2) +
  ";\n";
for (const [target, content] of [
  [output, result],
  [palette, paletteSource],
]) {
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== content)
      throw new Error("Design token adapter is out of date");
  } else writeFileSync(fileURLToPath(target), content);
}
